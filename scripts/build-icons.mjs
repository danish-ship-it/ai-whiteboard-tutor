const pascal = (n) => n.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const num = (v) => Number(v ?? 0);

function rectPath(x, y, w, h, rx) {
  if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`;
  const r = Math.min(rx, w / 2, h / 2);
  return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
}

function toPath([tag, a]) {
  switch (tag) {
    case "path": { const d = a.d.trim(); return d.startsWith("m") ? `M0 0${d}` : d; } // keep a leading relative move exact once joined
    case "circle": { const [cx, cy, r] = [num(a.cx), num(a.cy), num(a.r)]; return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`; }
    case "ellipse": { const [cx, cy, rx, ry] = [num(a.cx), num(a.cy), num(a.rx), num(a.ry)]; return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`; }
    case "rect": return rectPath(num(a.x), num(a.y), num(a.width), num(a.height), num(a.rx ?? a.ry));
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline": case "polygon": { const p = a.points.trim().split(/[\s,]+/); let d = `M${p[0]} ${p[1]}`; for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`; return tag === "polygon" ? d + "Z" : d; }
    default: throw new Error(`unsupported element ${tag}`);
  }
}

const out = {}; const missing = [];
